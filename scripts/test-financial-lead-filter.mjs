import { build } from 'esbuild';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
await build({entryPoints:['lib/financialLeadFilter.ts','lib/dashboardPeriods.ts'],bundle:true,platform:'node',format:'esm',outdir:'.tmp/financial-filter'});
const {isFinancialLead}=await import('../.tmp/financial-filter/financialLeadFilter.js');
const {dateBoundary}=await import('../.tmp/financial-filter/dashboardPeriods.js');
const start=dateBoundary('2026-10-01'),end=dateBoundary('2026-10-09',true);
const old={status:'Won',createdAt:'2026-06-01T00:00:00Z',wonAt:'2026-10-02T00:00:00Z'};
assert.equal(isFinancialLead(old,start,end),true);
assert.equal(isFinancialLead({...old,createdAt:'2026-10-02T00:00:00Z',wonAt:'2026-09-30T00:00:00Z'},start,end),false);
assert.equal(isFinancialLead({...old,legacy:true},start,end),false);
assert.equal(isFinancialLead({...old,status:'Lost'},start,end),false);
assert.equal(isFinancialLead({...old,wonAt:undefined,createdAt:'2026-10-02T00:00:00Z'},start,end),true);
assert.equal(isFinancialLead({...old,wonAt:'2026-09-30T18:30:00Z'},start,end),true);
assert.equal(isFinancialLead({...old,wonAt:'2026-10-09T18:29:59.999Z'},start,end),true);
assert.equal(isFinancialLead({...old,wonAt:'2026-10-09T18:30:00Z'},start,end),false);
assert.equal(isFinancialLead(old),true);
assert.equal(isFinancialLead({...old,legacy:true}),false);
assert.equal(isFinancialLead({...old,wonAt:'invalid'},start,end),false);
const dashboard=readFileSync('pages/Dashboard.tsx','utf8'),leads=readFileSync('pages/Leads.tsx','utf8');
assert.equal((dashboard.match(/handleNav\('\/leads\?status=Won&report=financial'\)/g)||[]).length,2);
assert.ok(dashboard.includes('isFinancialLead(l, range.start, range.end)'));
assert.ok(dashboard.includes('encodeURIComponent(viewAsAgent'));
assert.ok(leads.includes('isFinancialLead(l, createdFrom ? dateBoundary(createdFrom)'));
assert.ok(leads.includes('new Date(l.createdAt).getTime()'));
console.log('PASS: older enquiries won now, earlier wins excluded, legacy exclusion, missing Won date fallback, IST boundaries, All Time, dashboard/report shared predicate and employee navigation.');
